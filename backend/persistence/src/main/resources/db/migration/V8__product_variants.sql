-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V8: product variants + variant-level inventory
--
-- Unlocks "select weight / grind / packaging" on storefront product pages.
-- Each variant has its own SKU, optional price/weight override, and its own
-- inventory row.  Products without variants keep working unchanged — the
-- existing inventory row with variant_id = NULL is the "default" stock.
--
-- Tables added:
--   product_variant             — one SKU per variant of a product
--   product_variant_attribute   — key/value attributes (e.g. weight=500g, grind=medium)
--
-- Tables altered:
--   inventory                   — variant_id becomes a real FK to product_variant
--   cart_item                   — gains optional variant_id FK
--   order_item                  — gains variant_id + snapshot cols (variant_sku, variant_name)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Product variants
-- -----------------------------------------------------------------------------
CREATE TABLE product_variant (
    id                  BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    product_id          BIGINT         NOT NULL,
    sku                 VARCHAR(64)    NOT NULL,
    name                VARCHAR(255)   NOT NULL,
    price_override      DECIMAL(19,4)  NULL,
    weight_kg_override  DECIMAL(10,3)  NULL,
    active              BOOLEAN        NOT NULL DEFAULT TRUE,
    sort_order          INT            NOT NULL DEFAULT 0,
    created_at          TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at          TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_variant_sku UNIQUE (sku),
    CONSTRAINT fk_variant_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE
);

CREATE INDEX ix_variant_product ON product_variant (product_id);

CREATE TRIGGER trg_product_variant_updated_at
    BEFORE UPDATE ON product_variant
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Variant attributes (key/value pairs per variant)
-- e.g. (variant_id=1, attr_key='weight', attr_value='500g')
--      (variant_id=1, attr_key='grind',  attr_value='whole bean')
-- -----------------------------------------------------------------------------
CREATE TABLE product_variant_attribute (
    id          BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    variant_id  BIGINT         NOT NULL,
    attr_key    VARCHAR(100)   NOT NULL,
    attr_value  VARCHAR(255)   NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_variant_attr UNIQUE (variant_id, attr_key),
    CONSTRAINT fk_variant_attr_variant FOREIGN KEY (variant_id) REFERENCES product_variant(id) ON DELETE CASCADE
);

CREATE INDEX ix_variant_attr_variant ON product_variant_attribute (variant_id);

-- -----------------------------------------------------------------------------
-- Inventory: variant_id becomes a real FK
-- -----------------------------------------------------------------------------
ALTER TABLE inventory
    ADD CONSTRAINT fk_inventory_variant FOREIGN KEY (variant_id) REFERENCES product_variant(id) ON DELETE CASCADE;

-- -----------------------------------------------------------------------------
-- Cart item: add optional variant reference
-- -----------------------------------------------------------------------------
ALTER TABLE cart_item
    ADD COLUMN variant_id BIGINT NULL,
    ADD CONSTRAINT fk_cart_item_variant FOREIGN KEY (variant_id) REFERENCES product_variant(id) ON DELETE SET NULL;

CREATE INDEX ix_cart_item_variant ON cart_item (variant_id);

-- The existing unique constraint uk_cart_item_cart_product on (cart_id, product_id)
-- needs to include variant_id so the same product can be in the cart under
-- different variants.  Drop and recreate.
ALTER TABLE cart_item DROP CONSTRAINT uk_cart_item_cart_product;
ALTER TABLE cart_item
    ADD CONSTRAINT uk_cart_item_cart_product_variant UNIQUE (cart_id, product_id, variant_id);

-- -----------------------------------------------------------------------------
-- Order item: add variant snapshot columns
-- -----------------------------------------------------------------------------
ALTER TABLE order_item
    ADD COLUMN variant_id     BIGINT         NULL,
    ADD COLUMN variant_sku    VARCHAR(64)    NULL,
    ADD COLUMN variant_name   VARCHAR(255)   NULL;
