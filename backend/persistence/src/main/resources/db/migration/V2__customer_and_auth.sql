-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V2: customer + auth tables
--
-- Adds:
--   customer_group           — B2B tier definitions (retail / wholesale-t1 / …)
--   customer                 — end users (both B2C and B2B)
--   customer_address         — billing / shipping addresses
--   customer_refresh_token   — rotating refresh tokens (hashed at rest)
--   email_verification_token — one-shot token for email confirmation
--   password_reset_token     — one-shot token for password reset
--
-- Admin refresh tokens & MFA are deferred to V3 alongside the admin-API module.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Customer groups (B2B pricing tiers)
-- -----------------------------------------------------------------------------
CREATE TABLE customer_group (
    id               BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(64)    NOT NULL,
    name             VARCHAR(200)   NOT NULL,
    description      VARCHAR(500)   NULL,
    price_tier       VARCHAR(32)    NOT NULL DEFAULT 'RETAIL',
    moq_multiplier   DECIMAL(6,3)   NOT NULL DEFAULT 1.000,
    active           BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_customer_group_code UNIQUE (code)
);

CREATE TRIGGER trg_customer_group_updated_at
    BEFORE UPDATE ON customer_group
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Customers (both B2C and B2B)
-- -----------------------------------------------------------------------------
CREATE TABLE customer (
    id                    BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email                 VARCHAR(255)   NOT NULL,
    password_hash         VARCHAR(255)   NOT NULL,
    customer_type         VARCHAR(16)    NOT NULL DEFAULT 'B2C',
    status                VARCHAR(32)    NOT NULL DEFAULT 'PENDING_VERIFICATION',
    first_name            VARCHAR(120)   NULL,
    last_name             VARCHAR(120)   NULL,
    company_name          VARCHAR(255)   NULL,
    company_tin           VARCHAR(64)    NULL,
    company_vat_number    VARCHAR(64)    NULL,
    business_license_url  VARCHAR(500)   NULL,
    phone                 VARCHAR(64)    NULL,
    preferred_currency    CHAR(3)        NOT NULL DEFAULT 'USD',
    preferred_locale      VARCHAR(10)    NOT NULL DEFAULT 'en-US',
    group_id              BIGINT         NULL,
    email_verified_at     TIMESTAMP(3)   NULL,
    last_login_at         TIMESTAMP(3)   NULL,
    created_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    version               INT            NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_customer_email UNIQUE (email),
    CONSTRAINT fk_customer_group FOREIGN KEY (group_id) REFERENCES customer_group(id) ON DELETE SET NULL
);

CREATE INDEX ix_customer_status ON customer (status);
CREATE INDEX ix_customer_type   ON customer (customer_type);
CREATE INDEX ix_customer_group  ON customer (group_id);

CREATE TRIGGER trg_customer_updated_at
    BEFORE UPDATE ON customer
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Customer addresses
-- -----------------------------------------------------------------------------
CREATE TABLE customer_address (
    id             BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id    BIGINT         NOT NULL,
    address_type   VARCHAR(16)    NOT NULL,
    is_default     BOOLEAN        NOT NULL DEFAULT FALSE,
    full_name      VARCHAR(200)   NULL,
    company        VARCHAR(255)   NULL,
    street_line1   VARCHAR(255)   NOT NULL,
    street_line2   VARCHAR(255)   NULL,
    city           VARCHAR(120)   NOT NULL,
    region         VARCHAR(120)   NULL,
    postal_code    VARCHAR(32)    NULL,
    country_code   CHAR(2)        NOT NULL,
    phone          VARCHAR(64)    NULL,
    created_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT fk_addr_customer FOREIGN KEY (customer_id) REFERENCES customer(id) ON DELETE CASCADE
);

CREATE INDEX ix_addr_customer ON customer_address (customer_id);
CREATE INDEX ix_addr_country  ON customer_address (country_code);

CREATE TRIGGER trg_customer_address_updated_at
    BEFORE UPDATE ON customer_address
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Customer refresh tokens (rotating, hashed at rest)
-- -----------------------------------------------------------------------------
CREATE TABLE customer_refresh_token (
    id                CHAR(36)       NOT NULL,
    customer_id       BIGINT         NOT NULL,
    token_hash        CHAR(64)       NOT NULL,
    issued_at         TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    expires_at        TIMESTAMP(3)   NOT NULL,
    revoked_at        TIMESTAMP(3)   NULL,
    ip_address        VARCHAR(64)    NULL,
    user_agent        VARCHAR(500)   NULL,
    replaced_by_id    CHAR(36)       NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_refresh_customer FOREIGN KEY (customer_id) REFERENCES customer(id) ON DELETE CASCADE
);

CREATE INDEX ix_refresh_customer ON customer_refresh_token (customer_id);
CREATE INDEX ix_refresh_expiry   ON customer_refresh_token (expires_at);

-- -----------------------------------------------------------------------------
-- Email verification tokens (one-shot)
-- -----------------------------------------------------------------------------
CREATE TABLE email_verification_token (
    id             BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id    BIGINT         NOT NULL,
    token_hash     CHAR(64)       NOT NULL,
    expires_at     TIMESTAMP(3)   NOT NULL,
    used_at        TIMESTAMP(3)   NULL,
    created_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_evt_hash UNIQUE (token_hash),
    CONSTRAINT fk_evt_customer FOREIGN KEY (customer_id) REFERENCES customer(id) ON DELETE CASCADE
);

CREATE INDEX ix_evt_customer ON email_verification_token (customer_id);

-- -----------------------------------------------------------------------------
-- Password reset tokens (one-shot)
-- -----------------------------------------------------------------------------
CREATE TABLE password_reset_token (
    id             BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id    BIGINT         NOT NULL,
    token_hash     CHAR(64)       NOT NULL,
    expires_at     TIMESTAMP(3)   NOT NULL,
    used_at        TIMESTAMP(3)   NULL,
    ip_address     VARCHAR(64)    NULL,
    created_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_prt_hash UNIQUE (token_hash),
    CONSTRAINT fk_prt_customer FOREIGN KEY (customer_id) REFERENCES customer(id) ON DELETE CASCADE
);

CREATE INDEX ix_prt_customer ON password_reset_token (customer_id);

