-- V14: CMS pages and banners for content management
-- Supports static pages (About, FAQ, Terms, etc.) and homepage banners.

CREATE TABLE cms_page (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    slug            VARCHAR(120) NOT NULL,
    title           VARCHAR(200) NOT NULL,
    body_html       TEXT         NULL,
    seo_title       VARCHAR(200) NULL,
    seo_description VARCHAR(500) NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    sort_order      INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version         INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_cms_page_slug UNIQUE (slug)
);

CREATE TRIGGER trg_cms_page_updated_at
    BEFORE UPDATE ON cms_page
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE TABLE cms_banner (
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    placement   VARCHAR(40)  NOT NULL,
    title       VARCHAR(200) NULL,
    image_url   VARCHAR(500) NOT NULL,
    alt_text    VARCHAR(300) NULL,
    link_url    VARCHAR(500) NULL,
    active_from TIMESTAMP    NULL,
    active_to   TIMESTAMP    NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version     INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);

CREATE INDEX idx_cms_banner_placement ON cms_banner (placement, active, sort_order);

CREATE TRIGGER trg_cms_banner_updated_at
    BEFORE UPDATE ON cms_banner
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();
