-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V5: cart + order model
--
-- This migration lays the foundation for checkout (Phase 3b). It adds:
--
--   cart                   — one active cart per customer (Phase 3a wires this up)
--   cart_item              — line items in a cart, with price snapshot
--   checkout_order         — placed orders (table named `checkout_order` because
--                            `order` is a reserved word in SQL)
--   order_item             — snapshotted lines on a placed order
--   order_status_event     — status-change audit log (order id, from, to, source)
--
-- Foreign keys:
--   cart.customer_id       → customer.id       (unique — one active cart per customer)
--   cart_item.cart_id      → cart.id           (CASCADE delete)
--   cart_item.product_id   → product.id
--
--   checkout_order.customer_id         → customer.id
--   checkout_order.ship_to_address_id  → customer_address.id
--   checkout_order.bill_to_address_id  → customer_address.id
--   order_item.order_id                → checkout_order.id  (CASCADE delete)
--   order_item.product_id              → product.id
--   order_status_event.order_id        → checkout_order.id  (CASCADE delete)
--
-- Reserved for later phases:
--   Guest carts (session-keyed rather than customer-keyed) — Phase 3c if needed
--   Coupons / discounts — Phase 4
--   Shipping methods table — Phase 4
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Cart (1:1 with customer for MVP)
-- -----------------------------------------------------------------------------
CREATE TABLE cart (
    id             BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id    BIGINT       NOT NULL,
    currency       CHAR(3)      NOT NULL DEFAULT 'USD',
    created_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_cart_customer UNIQUE (customer_id),
    CONSTRAINT fk_cart_customer FOREIGN KEY (customer_id) REFERENCES customer(id) ON DELETE CASCADE
);

CREATE TRIGGER trg_cart_updated_at
    BEFORE UPDATE ON cart
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Cart lines. Price is snapshotted at add-time so a mid-session price change
-- doesn't silently mutate the cart total. Re-resolution on checkout is done
-- explicitly in Phase 3b OrderService.createFromCart().
-- -----------------------------------------------------------------------------
CREATE TABLE cart_item (
    id               BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    cart_id          BIGINT         NOT NULL,
    product_id       BIGINT         NOT NULL,
    quantity         DECIMAL(10,3)  NOT NULL,
    unit_price_snap  DECIMAL(19,4)  NOT NULL,
    currency         CHAR(3)        NOT NULL DEFAULT 'USD',
    added_at         TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_cart_item_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT fk_cart_item_cart    FOREIGN KEY (cart_id)    REFERENCES cart(id)    ON DELETE CASCADE,
    CONSTRAINT fk_cart_item_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE
);

CREATE INDEX ix_cart_item_product ON cart_item (product_id);

CREATE TRIGGER trg_cart_item_updated_at
    BEFORE UPDATE ON cart_item
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- checkout_order — placed orders (the customer-visible, invoiced kind).
-- Money columns are DECIMAL(19,4) for full-precision multi-currency support.
-- -----------------------------------------------------------------------------
CREATE TABLE checkout_order (
    id                    BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    uuid                  CHAR(36)       NOT NULL,
    invoice_number        VARCHAR(40)    NOT NULL,
    customer_id           BIGINT         NOT NULL,
    status                VARCHAR(24)    NOT NULL DEFAULT 'PENDING_PAYMENT',

    -- Money
    currency              CHAR(3)        NOT NULL,
    subtotal              DECIMAL(19,4)  NOT NULL DEFAULT 0,
    tax_total             DECIMAL(19,4)  NOT NULL DEFAULT 0,
    shipping_total        DECIMAL(19,4)  NOT NULL DEFAULT 0,
    discount_total        DECIMAL(19,4)  NOT NULL DEFAULT 0,
    grand_total           DECIMAL(19,4)  NOT NULL DEFAULT 0,

    -- Addresses (snapshot-referenced from customer_address; a later phase may
    -- freeze the address text onto the order to preserve invoicing history)
    ship_to_address_id    BIGINT         NULL,
    bill_to_address_id    BIGINT         NULL,

    -- Payment ref (populated on CyberSource callback in Phase 3b)
    payment_reference     VARCHAR(120)   NULL,
    payment_provider      VARCHAR(40)    NULL,

    -- Timestamps
    placed_at             TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    paid_at               TIMESTAMP(3)   NULL,
    cancelled_at          TIMESTAMP(3)   NULL,
    updated_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    customer_notes        VARCHAR(1000)  NULL,
    internal_notes        VARCHAR(1000)  NULL,

    PRIMARY KEY (id),
    CONSTRAINT uk_order_uuid           UNIQUE (uuid),
    CONSTRAINT uk_order_invoice_number UNIQUE (invoice_number),

    CONSTRAINT fk_order_customer  FOREIGN KEY (customer_id)         REFERENCES customer(id),
    CONSTRAINT fk_order_ship_to   FOREIGN KEY (ship_to_address_id)  REFERENCES customer_address(id) ON DELETE SET NULL,
    CONSTRAINT fk_order_bill_to   FOREIGN KEY (bill_to_address_id)  REFERENCES customer_address(id) ON DELETE SET NULL
);

CREATE INDEX ix_order_customer ON checkout_order (customer_id);
CREATE INDEX ix_order_status   ON checkout_order (status);
CREATE INDEX ix_order_placed   ON checkout_order (placed_at);

CREATE TRIGGER trg_checkout_order_updated_at
    BEFORE UPDATE ON checkout_order
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- order_item — snapshotted lines on a placed order. Product name + SKU are
-- copied here so if the catalog is later renamed or archived the invoice is
-- still readable.
-- -----------------------------------------------------------------------------
CREATE TABLE order_item (
    id               BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    order_id         BIGINT         NOT NULL,
    product_id       BIGINT         NOT NULL,
    sku              VARCHAR(64)    NOT NULL,
    name             VARCHAR(255)   NOT NULL,
    unit_price       DECIMAL(19,4)  NOT NULL,
    quantity         DECIMAL(10,3)  NOT NULL,
    tax_rate         DECIMAL(6,4)   NOT NULL DEFAULT 0,
    tax_amount       DECIMAL(19,4)  NOT NULL DEFAULT 0,
    line_total       DECIMAL(19,4)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_order_item_order   FOREIGN KEY (order_id)   REFERENCES checkout_order(id) ON DELETE CASCADE,
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product(id)
);

CREATE INDEX ix_order_item_order   ON order_item (order_id);
CREATE INDEX ix_order_item_product ON order_item (product_id);

-- -----------------------------------------------------------------------------
-- order_status_event — append-only status-change log.
-- Populated whenever the order transitions state, either via customer action
-- (cancel), admin action (mark shipped), or system event (payment webhook).
-- -----------------------------------------------------------------------------
CREATE TABLE order_status_event (
    id               BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    order_id         BIGINT        NOT NULL,
    from_status      VARCHAR(24)   NULL,
    to_status        VARCHAR(24)   NOT NULL,
    source           VARCHAR(24)   NOT NULL,
    actor_id         BIGINT        NULL,
    note             VARCHAR(500)  NULL,
    occurred_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT fk_ose_order FOREIGN KEY (order_id) REFERENCES checkout_order(id) ON DELETE CASCADE
);

CREATE INDEX ix_ose_order     ON order_status_event (order_id, occurred_at);
CREATE INDEX ix_ose_to_status ON order_status_event (to_status);
