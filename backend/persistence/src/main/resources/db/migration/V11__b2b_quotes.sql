-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V11: B2B quote flow
--
-- Adds the quote + quote_item tables so B2B buyers can request a formal quote
-- from their cart, admins can review/edit proposed pricing, send the quote
-- back, and the customer can accept it — converting it into an order.
--
-- Lifecycle:
--   DRAFT → SUBMITTED → UNDER_REVIEW → SENT → ACCEPTED → CONVERTED
--                                       └→ REJECTED
--                                       └→ EXPIRED
--
-- Foreign keys:
--   quote.customer_id          → customer.id
--   quote.converted_order_id   → checkout_order.id  (nullable, set on accept)
--   quote_item.quote_id        → quote.id           (CASCADE delete)
--   quote_item.product_id      → product.id
--   quote_item.variant_id      → product_variant.id (nullable)
-- =============================================================================

CREATE TABLE quote (
    id                 BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    uuid               CHAR(36)     NOT NULL,
    customer_id        BIGINT       NOT NULL,
    status             VARCHAR(24)  NOT NULL DEFAULT 'DRAFT',
    currency           CHAR(3)      NOT NULL DEFAULT 'USD',
    subtotal           DECIMAL(19,4) NOT NULL DEFAULT 0,
    tax_total          DECIMAL(19,4) NOT NULL DEFAULT 0,
    shipping_total     DECIMAL(19,4) NOT NULL DEFAULT 0,
    grand_total        DECIMAL(19,4) NOT NULL DEFAULT 0,
    customer_notes     VARCHAR(2000) NULL,
    admin_notes        VARCHAR(2000) NULL,
    valid_until        TIMESTAMP(3) NULL,
    converted_order_id BIGINT       NULL,
    created_at         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    version            INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_quote_uuid UNIQUE (uuid),
    CONSTRAINT fk_quote_customer FOREIGN KEY (customer_id) REFERENCES customer(id) ON DELETE CASCADE,
    CONSTRAINT fk_quote_order FOREIGN KEY (converted_order_id) REFERENCES checkout_order(id) ON DELETE SET NULL
);

CREATE INDEX idx_quote_customer ON quote (customer_id);
CREATE INDEX idx_quote_status   ON quote (status);

CREATE TRIGGER trg_quote_updated_at
    BEFORE UPDATE ON quote
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE TABLE quote_item (
    id               BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    quote_id         BIGINT         NOT NULL,
    product_id       BIGINT         NOT NULL,
    variant_id       BIGINT         NULL,
    sku              VARCHAR(64)    NOT NULL,
    name             VARCHAR(255)   NOT NULL,
    variant_sku      VARCHAR(64)    NULL,
    variant_name     VARCHAR(255)   NULL,
    quantity         DECIMAL(10,3)  NOT NULL,
    proposed_unit_price DECIMAL(19,4) NOT NULL,
    line_total       DECIMAL(19,4)  NOT NULL DEFAULT 0,
    created_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_quote_item_quote_product_variant UNIQUE (quote_id, product_id, variant_id),
    CONSTRAINT fk_quote_item_quote FOREIGN KEY (quote_id) REFERENCES quote(id) ON DELETE CASCADE,
    CONSTRAINT fk_quote_item_product FOREIGN KEY (product_id) REFERENCES product(id),
    CONSTRAINT fk_quote_item_variant FOREIGN KEY (variant_id) REFERENCES product_variant(id) ON DELETE SET NULL
);

CREATE TRIGGER trg_quote_item_updated_at
    BEFORE UPDATE ON quote_item
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();
