-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V7: order refunds
--
-- Support has had no way to refund a paid order since Phase 3b — the whole
-- customer service refund workflow lived in a spreadsheet. This migration
-- adds the persistence layer for the flow and hooks the two new order
-- states (PARTIALLY_REFUNDED / REFUNDED) into the aggregate on the parent
-- order row.
--
-- Tables:
--   order_refund               — one row per refund attempt against an
--                                order. Both full and partial refunds
--                                land here. Rows are append-only from
--                                the admin API — a mis-issued refund
--                                should be resolved with a compensating
--                                positive charge (out-of-band, since our
--                                CyberSource integration is refund-only)
--                                or, in dev / prod-emergency, a manual
--                                DB correction.
--
-- Columns added to checkout_order:
--   refunded_total             — cumulative cents refunded across all
--                                order_refund rows for the order. Denormalised
--                                for cheap reads on the /orders list + the
--                                admin detail page; the refund service keeps
--                                it consistent inside the same @Transactional
--                                boundary as the order_refund insert.
--
-- Design notes:
--
--   * Currency lives on the parent order row (checkout_order.currency).
--     A refund is always in the order's currency; storing it on the child
--     row would be redundant and risk drift.
--
--   * gateway_provider + gateway_reference. We record what actually
--     processed the refund. For CyberSource REST API refunds this is
--     ("CYBERSOURCE", "<their refund id>"). For manual / offline refunds
--     (used in dev when creds aren't wired, and for edge-case ops
--     interventions like a cash refund at the warehouse) this is
--     ("MANUAL", NULL) with the admin's note explaining what happened.
--     The parent order's payment_reference is a separate column and is
--     NOT overwritten — it still points at the original capture.
--
--   * status column on order_refund. A refund lives inside a distributed
--     saga (admin API ↔ CyberSource REST). We record SUCCEEDED / FAILED
--     so a retry of a failed refund does not double-refund the customer.
--     FAILED rows still occupy the audit log so support can see what was
--     attempted.
--
--   * ON DELETE for the order FK: RESTRICT. Deleting a paid order is
--     already impossible upstream (the transition table has no path to
--     a non-terminal-cancelled state after PAID); restricting the FK
--     makes that guarantee explicit at the schema level and stops an
--     ill-considered manual DELETE from silently orphaning the ledger.
--
--   * initiated_by_admin_id: the admin_user.id that clicked "Refund" in
--     the UI. NULL for the seed / dev-mode auto-refunds. FK is soft
--     (SET NULL on delete) so removing an admin user doesn't wipe out
--     the audit trail.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- order_refund
-- -----------------------------------------------------------------------------
CREATE TABLE order_refund (
    id                    BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    uuid                  CHAR(36)       NOT NULL,
    order_id              BIGINT         NOT NULL,

    amount                DECIMAL(19,4)  NOT NULL,
    reason                VARCHAR(1000)  NOT NULL,

    status                VARCHAR(32)    NOT NULL,
    gateway_provider      VARCHAR(64)    NULL,
    gateway_reference     VARCHAR(200)   NULL,
    gateway_error_code    VARCHAR(64)    NULL,
    gateway_error_message VARCHAR(1000)  NULL,

    initiated_by_admin_id BIGINT         NULL,
    created_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    PRIMARY KEY (id),
    CONSTRAINT uk_order_refund_uuid UNIQUE (uuid),
    CONSTRAINT fk_order_refund_order FOREIGN KEY (order_id)
        REFERENCES checkout_order(id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_refund_admin FOREIGN KEY (initiated_by_admin_id)
        REFERENCES admin_user(id) ON DELETE SET NULL
);

CREATE INDEX ix_order_refund_order  ON order_refund (order_id, created_at);
CREATE INDEX ix_order_refund_status ON order_refund (status);

CREATE TRIGGER trg_order_refund_updated_at
    BEFORE UPDATE ON order_refund
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- checkout_order: cache the aggregate so the admin list can show
-- "Refunded 40.00 / 100.00" without a join.
-- -----------------------------------------------------------------------------
ALTER TABLE checkout_order
    ADD COLUMN refunded_total DECIMAL(19,4) NOT NULL DEFAULT 0;
