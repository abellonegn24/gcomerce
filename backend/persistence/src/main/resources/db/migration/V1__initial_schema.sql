-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V1: initial schema slice
--
-- Scope: bare-minimum tables needed for Phase 1 (auth, settings, tax profile).
-- Subsequent migrations (V2, V3, ...) will add catalog, cart, order, payment.
-- All string columns are VARCHAR; monetary values use DECIMAL(19,4).
