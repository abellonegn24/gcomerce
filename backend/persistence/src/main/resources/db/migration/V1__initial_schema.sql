-- Trigger function for auto-updating updated_at columns (replaces MySQL's
-- ON UPDATE CURRENT_TIMESTAMP clause which PostgreSQL does not support).
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP(3);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- -----------------------------------------------------------------------------
-- Settings — key/value store for platform-wide configuration
-- -----------------------------------------------------------------------------
CREATE TABLE setting (
    key             VARCHAR(120)   NOT NULL,
    value_json      JSONB          NOT NULL,
    updated_by      BIGINT         NULL,
    updated_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (key)
);

CREATE TRIGGER trg_setting_updated_at
    BEFORE UPDATE ON setting
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Roles & permissions (admin-side RBAC)
-- -----------------------------------------------------------------------------
CREATE TABLE role (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(64)    NOT NULL,
    description     VARCHAR(255)   NULL,
    created_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_role_name UNIQUE (name)
);

CREATE TABLE permission (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(120)   NOT NULL,
    description     VARCHAR(255)   NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_permission_code UNIQUE (code)
);

CREATE TABLE role_permission (
    role_id         BIGINT         NOT NULL,
    permission_id   BIGINT         NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_rp_role       FOREIGN KEY (role_id)       REFERENCES role(id)       ON DELETE CASCADE,
    CONSTRAINT fk_rp_permission FOREIGN KEY (permission_id) REFERENCES permission(id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- Admin users
-- -----------------------------------------------------------------------------
CREATE TABLE admin_user (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email           VARCHAR(255)   NOT NULL,
    password_hash   VARCHAR(255)   NOT NULL,
    full_name       VARCHAR(200)   NOT NULL,
    role_id         BIGINT         NOT NULL,
    status          VARCHAR(32)    NOT NULL DEFAULT 'ACTIVE',
    mfa_secret      VARCHAR(255)   NULL,
    last_login_at   TIMESTAMP(3)   NULL,
    created_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_admin_user_email UNIQUE (email),
    CONSTRAINT fk_admin_user_role FOREIGN KEY (role_id) REFERENCES role(id)
);

CREATE INDEX ix_admin_user_role ON admin_user (role_id);

CREATE TRIGGER trg_admin_user_updated_at
    BEFORE UPDATE ON admin_user
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Company tax profile (single-row config in MVP; table for auditability)
-- Aligns with FR-TAX-01 in the delivery plan.
-- -----------------------------------------------------------------------------
CREATE TABLE company_tax_profile (
    id                          BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    legal_name                  VARCHAR(255)   NOT NULL,
    tin                         VARCHAR(64)    NULL,
    vat_number                  VARCHAR(64)    NULL,
    address                     VARCHAR(500)   NULL,
    phone                       VARCHAR(64)    NULL,
    email                       VARCHAR(255)   NULL,
    logo_url                    VARCHAR(500)   NULL,
    authorized_signatory_name   VARCHAR(200)   NULL,
    authorized_signatory_title  VARCHAR(120)   NULL,
    fiscal_year_start_month     SMALLINT       NOT NULL DEFAULT 7,
    active                      BOOLEAN        NOT NULL DEFAULT TRUE,
    updated_at                  TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id)
);

CREATE TRIGGER trg_company_tax_profile_updated_at
    BEFORE UPDATE ON company_tax_profile
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Tax classes and rules (FR-TAX-02)
-- -----------------------------------------------------------------------------
CREATE TABLE tax_class (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(32)    NOT NULL,
    name            VARCHAR(120)   NOT NULL,
    description     VARCHAR(500)   NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_tax_class_code UNIQUE (code)
);

CREATE TABLE tax_rule (
    id                BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tax_class_id      BIGINT         NOT NULL,
    country_code      CHAR(2)        NULL,
    rate_percent      DECIMAL(6,3)   NOT NULL DEFAULT 0,
    zero_rated        BOOLEAN        NOT NULL DEFAULT FALSE,
    zero_rated_reason VARCHAR(255)   NULL,
    effective_from    DATE           NOT NULL,
    effective_to      DATE           NULL,
    active            BOOLEAN        NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT fk_tax_rule_class FOREIGN KEY (tax_class_id) REFERENCES tax_class(id)
);

CREATE INDEX ix_tax_rule_class   ON tax_rule (tax_class_id);
CREATE INDEX ix_tax_rule_country ON tax_rule (country_code);

-- -----------------------------------------------------------------------------
-- Invoice sequence — atomic, gap-free per fiscal year (FR-TAX-06)
-- Issuance uses SELECT ... FOR UPDATE to serialize concurrent invoicing.
-- -----------------------------------------------------------------------------
CREATE TABLE invoice_sequence (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    doc_type        VARCHAR(20)    NOT NULL,
    fiscal_year     INT            NOT NULL,
    prefix          VARCHAR(20)    NOT NULL,
    current_value   BIGINT         NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_invoice_seq UNIQUE (doc_type, fiscal_year)
);

