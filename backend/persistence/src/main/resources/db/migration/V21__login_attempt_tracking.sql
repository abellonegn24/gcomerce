-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V21: login attempt tracking & account lockout
--
-- INSA CWE-307 remediation: the storefront /auth/login endpoint accepted
-- repeated invalid password attempts against the same account without any
-- account-level barrier. This migration adds per-account failed-attempt
-- counters and lockout timestamps to both `customer` and `admin_user`, plus
-- an audit log table for monitoring (the auditor explicitly required that
-- failed authentications be "logged and monitored").
--
-- Lockout policy is enforced in `LoginAttemptService` (web-common):
--   * after `max-failed-attempts` consecutive failures the account is locked
--     until `locked_until`;
--   * lockout duration is progressive — each successive lockout doubles,
--     capped at `max-lockout-seconds` (defaults 15 min → 30 min → 60 min).
--   * a successful login resets `failed_login_attempts`, `locked_until`, and
--     `lockout_sequence` to 0 / NULL / 0.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- customer: failed-attempt counter + lockout window + lockout sequence
-- -----------------------------------------------------------------------------
ALTER TABLE customer
    ADD COLUMN failed_login_attempts INT            NOT NULL DEFAULT 0,
    ADD COLUMN locked_until          TIMESTAMP(3)   NULL,
    ADD COLUMN lockout_sequence      INT            NOT NULL DEFAULT 0;

-- Partial index: only locked rows are interesting; keeps the index tiny.
CREATE INDEX ix_customer_locked_until ON customer (locked_until)
    WHERE locked_until IS NOT NULL;

-- -----------------------------------------------------------------------------
-- admin_user: same three columns (admin login + verify-mfa are both hardened)
-- -----------------------------------------------------------------------------
ALTER TABLE admin_user
    ADD COLUMN failed_login_attempts INT            NOT NULL DEFAULT 0,
    ADD COLUMN locked_until          TIMESTAMP(3)   NULL,
    ADD COLUMN lockout_sequence      INT            NOT NULL DEFAULT 0;

CREATE INDEX ix_admin_user_locked_until ON admin_user (locked_until)
    WHERE locked_until IS NOT NULL;

-- -----------------------------------------------------------------------------
-- login_attempt_log: append-only audit trail of every login attempt.
-- Satisfies the INSA "logged and monitored" requirement and feeds future
-- alerting / admin dashboards. account_type is 'CUSTOMER' or 'ADMIN'.
-- -----------------------------------------------------------------------------
CREATE TABLE login_attempt_log (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    account_type    VARCHAR(16)    NOT NULL,
    email           VARCHAR(255)   NOT NULL,
    ip_address      VARCHAR(64)    NULL,
    user_agent      VARCHAR(500)   NULL,
    success         BOOLEAN        NOT NULL,
    attempted_at    TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id)
);

CREATE INDEX ix_login_attempt_email_time ON login_attempt_log (email, attempted_at);
CREATE INDEX ix_login_attempt_ip_time    ON login_attempt_log (ip_address, attempted_at);
CREATE INDEX ix_login_attempt_time       ON login_attempt_log (attempted_at);
