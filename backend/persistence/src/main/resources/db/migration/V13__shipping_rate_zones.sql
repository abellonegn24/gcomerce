-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V13: per-country shipping rate zones
--
-- Allows admins to override the base_cost + per_kg_rate of a shipping_method
-- for specific destination countries. For example, INTL_STANDARD can have a
-- higher per-kg rate for remote destinations (AU, NZ) than for near ones (KE,
-- DJ). When no zone exists for a (method, country) pair, the method's default
-- rates apply — so existing behaviour is unchanged until zones are configured.
--
-- Design:
--   * One row = one country-specific rate override for one shipping method.
--   * UNIQUE(method_id, country_code) prevents duplicate overrides.
--   * country_code is ISO-3166 alpha-2 (e.g. US, GB, ET, KE).
--   * base_cost / per_kg_rate are both nullable — NULL means "inherit the
--     method's default" for that component. This lets an admin override only
--     the per-kg rate while keeping the base cost, or vice versa.
--   * min_days / max_days override the transit ETA for display on the picker.
--   * active flag lets admins soft-disable a zone without deleting it.
-- =============================================================================

CREATE TABLE shipping_rate_zone (
    id              BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    shipping_method_id BIGINT      NOT NULL,
    country_code    CHAR(2)        NOT NULL,
    base_cost       DECIMAL(19,4)  NULL,
    per_kg_rate     DECIMAL(19,4)  NULL,
    min_days        INT            NULL,
    max_days        INT            NULL,
    active          BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_zone_method_country UNIQUE (shipping_method_id, country_code),
    CONSTRAINT fk_zone_shipping_method
        FOREIGN KEY (shipping_method_id) REFERENCES shipping_method(id) ON DELETE CASCADE
);

CREATE INDEX ix_zone_country ON shipping_rate_zone (country_code);

CREATE TRIGGER trg_shipping_rate_zone_updated_at
    BEFORE UPDATE ON shipping_rate_zone
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();
