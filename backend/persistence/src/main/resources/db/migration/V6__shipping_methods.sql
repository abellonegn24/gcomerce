-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V6: shipping methods + calculator wiring
--
-- Closes the biggest MVP gap left over from Phase 3: Order.shippingTotal was
-- hardcoded to 0 because there was no method table to price against. This
-- migration adds:
--
--   shipping_method               — admin-managed rate cards
--                                   (base_cost + per_kg_rate, per-currency)
--   checkout_order.shipping_method_id      — FK to the chosen method (NULL for
--                                            legacy Phase 3 orders + true FCA
--                                            / pickup orders)
--   checkout_order.shipping_method_code    — snapshot at placement so future
--                                            rename/deletion of the method
--                                            does not corrupt the invoice
--   checkout_order.shipping_method_name    — snapshot at placement (same
--                                            reason)
--
-- Design decisions:
--   * Weight-based tiered cost model — the simplest rate card that is
--     actually useful. Flat base for small parcels, per-kg surcharge for
--     heavier orders. More sophisticated banded pricing (e.g. "3–5 kg = X,
--     5–10 kg = Y") is Phase 5 if needed.
--   * Currency-scoped. A shipping_method targets exactly one currency; when
--     the storefront quotes for a USD cart it filters by currency=USD. This
--     prevents mixed-currency inconsistencies (a USD parcel priced against
--     an ETB per-kg rate would be nonsense).
--   * Snapshot code+name onto the order. Deleting or renaming a method in
--     future must not break invoice re-printing.
--   * On ON DELETE for the FK: SET NULL. Deleting a shipping method should
--     not cascade-delete historical orders; the snapshot columns preserve
--     the customer-visible information anyway.
--
-- Seeded defaults (currency USD, valid immediately):
--   * DOMESTIC_ROAD  — Ethiopia domestic road freight, base $8.00 + $0.60/kg
--   * INTL_STANDARD  — International standard air, base $35.00 + $6.50/kg
--   * INTL_EXPRESS   — International express (DHL-tier), base $55.00 + $9.00/kg
--   * PICKUP_FREE    — Customer pickup at Addis warehouse, base $0.00 + $0/kg
-- =============================================================================

-- -----------------------------------------------------------------------------
-- shipping_method
-- -----------------------------------------------------------------------------
CREATE TABLE shipping_method (
    id               BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(64)    NOT NULL,
    name             VARCHAR(200)   NOT NULL,
    description      VARCHAR(1000)  NULL,
    currency         CHAR(3)        NOT NULL,
    base_cost        DECIMAL(19,4)  NOT NULL DEFAULT 0,
    per_kg_rate      DECIMAL(19,4)  NOT NULL DEFAULT 0,
    min_days         INT            NULL,
    max_days         INT            NULL,
    active           BOOLEAN        NOT NULL DEFAULT TRUE,
    sort_order       INT            NOT NULL DEFAULT 100,
    created_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_shipping_method_code_currency UNIQUE (code, currency)
);

CREATE INDEX ix_shipping_method_active_currency ON shipping_method (active, currency);

CREATE TRIGGER trg_shipping_method_updated_at
    BEFORE UPDATE ON shipping_method
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- checkout_order: bind the chosen method + snapshot the code/name for history.
-- All new columns are nullable so already-placed Phase 3 orders survive the
-- migration untouched (their shipping_total is 0, matching what they paid).
-- -----------------------------------------------------------------------------
ALTER TABLE checkout_order
    ADD COLUMN shipping_method_id   BIGINT       NULL,
    ADD COLUMN shipping_method_code VARCHAR(64)  NULL,
    ADD COLUMN shipping_method_name VARCHAR(200) NULL,
    ADD CONSTRAINT fk_order_shipping_method
        FOREIGN KEY (shipping_method_id) REFERENCES shipping_method(id) ON DELETE SET NULL;

CREATE INDEX ix_order_shipping_method ON checkout_order (shipping_method_id);

