-- =============================================================================
-- V9: Coupons / discount codes
--
-- Supports percentage and fixed-amount coupons, usage limits, expiry,
-- per-customer limits, min-subtotal threshold, and free-shipping flag.
-- Redemptions are tracked in coupon_redemption for audit + enforcement.
-- =============================================================================

CREATE TABLE coupon (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(64)  NOT NULL,
    description     VARCHAR(500),
    discount_type   VARCHAR(20)  NOT NULL,
    discount_value  DECIMAL(19, 4) NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    min_subtotal    DECIMAL(19, 4),
    free_shipping   BOOLEAN      NOT NULL DEFAULT FALSE,
    max_redemptions INT,
    max_per_customer INT,
    redeemed_count  INT          NOT NULL DEFAULT 0,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    starts_at       TIMESTAMP    NULL,
    expires_at      TIMESTAMP    NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_coupon_code UNIQUE (code)
);

CREATE TRIGGER trg_coupon_updated_at
    BEFORE UPDATE ON coupon
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE TABLE coupon_redemption (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    coupon_id       BIGINT       NOT NULL,
    order_id        BIGINT       NOT NULL,
    customer_id     BIGINT       NOT NULL,
    code            VARCHAR(64)  NOT NULL,
    discount_amount DECIMAL(19, 4) NOT NULL,
    redeemed_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_redemption_order UNIQUE (order_id),
    CONSTRAINT fk_redemption_coupon   FOREIGN KEY (coupon_id)   REFERENCES coupon (id)          ON DELETE RESTRICT,
    CONSTRAINT fk_redemption_order    FOREIGN KEY (order_id)    REFERENCES checkout_order (id)   ON DELETE RESTRICT,
    CONSTRAINT fk_redemption_customer FOREIGN KEY (customer_id) REFERENCES customer (id)         ON DELETE CASCADE
);

CREATE INDEX idx_redemption_coupon   ON coupon_redemption (coupon_id);
CREATE INDEX idx_redemption_customer ON coupon_redemption (customer_id);

-- Add coupon snapshot columns to checkout_order for historical reference.
ALTER TABLE checkout_order
    ADD COLUMN coupon_code         VARCHAR(64) NULL,
    ADD COLUMN coupon_description  VARCHAR(500) NULL,
    ADD COLUMN coupon_discount     DECIMAL(19, 4) NOT NULL DEFAULT 0;
