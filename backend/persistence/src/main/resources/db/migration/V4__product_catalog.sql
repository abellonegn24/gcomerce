-- =============================================================================
-- Gadaa Istar E-Commerce — Flyway V4: product catalog slice
--
-- Adds:
--   product              — the canonical catalog item (a coffee, spice, dairy line, …)
--   product_media        — images (and later video) attached to a product
--   price_list           — per-customer-group price sheet
--   price_list_entry     — one row per (price_list, product, min-qty tier)
--   inventory            — on-hand + reserved stock per product
--
-- Deferred (Phase 2.3b or later):
--   product_variant  — variant SKUs (250 g / 500 g / 1 kg, whole / ground, …)
--                      Kept out for now: MVP treats each product as single-SKU.
--                      Adding it later is additive: product_variant.product_id FK
--                      plus optional inventory.variant_id column.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Products
-- -----------------------------------------------------------------------------
CREATE TABLE product (
    id                    BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    sku                   VARCHAR(64)    NOT NULL,
    slug                  VARCHAR(200)   NOT NULL,
    name                  VARCHAR(255)   NOT NULL,
    short_description     VARCHAR(500)   NULL,
    description           TEXT           NULL,
    category              VARCHAR(32)    NOT NULL,
    status                VARCHAR(16)    NOT NULL DEFAULT 'DRAFT',
    weight_kg             DECIMAL(10,3)  NULL,
    hs_code               VARCHAR(32)    NULL,
    origin_country        CHAR(2)        NOT NULL DEFAULT 'ET',
    tax_class_id          BIGINT         NULL,
    base_currency         CHAR(3)        NOT NULL DEFAULT 'USD',
    base_price            DECIMAL(19,4)  NOT NULL,
    cost_price            DECIMAL(19,4)  NULL,
    min_order_quantity    DECIMAL(10,3)  NOT NULL DEFAULT 1.000,
    packaging_notes       VARCHAR(500)   NULL,
    created_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    version               INT            NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_product_sku  UNIQUE (sku),
    CONSTRAINT uk_product_slug UNIQUE (slug),
    CONSTRAINT fk_product_tax_class FOREIGN KEY (tax_class_id) REFERENCES tax_class(id) ON DELETE SET NULL
);

CREATE INDEX ix_product_category    ON product (category);
CREATE INDEX ix_product_status      ON product (status);
CREATE INDEX ix_product_tax_class   ON product (tax_class_id);

CREATE TRIGGER trg_product_updated_at
    BEFORE UPDATE ON product
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Product media
-- -----------------------------------------------------------------------------
CREATE TABLE product_media (
    id             BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    product_id     BIGINT         NOT NULL,
    url            VARCHAR(500)   NOT NULL,
    alt_text       VARCHAR(255)   NULL,
    media_type     VARCHAR(16)    NOT NULL DEFAULT 'IMAGE',
    is_primary     BOOLEAN        NOT NULL DEFAULT FALSE,
    sort_order     INT            NOT NULL DEFAULT 0,
    created_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT fk_media_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE
);

CREATE INDEX ix_media_product ON product_media (product_id);

-- -----------------------------------------------------------------------------
-- Price lists (per customer group)
-- -----------------------------------------------------------------------------
CREATE TABLE price_list (
    id                    BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_group_id     BIGINT         NOT NULL,
    name                  VARCHAR(200)   NOT NULL,
    currency              CHAR(3)        NOT NULL DEFAULT 'USD',
    active                BOOLEAN        NOT NULL DEFAULT TRUE,
    effective_from        DATE           NULL,
    effective_to          DATE           NULL,
    created_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at            TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT fk_price_list_group FOREIGN KEY (customer_group_id) REFERENCES customer_group(id) ON DELETE CASCADE
);

CREATE INDEX ix_price_list_group    ON price_list (customer_group_id);
CREATE INDEX ix_price_list_currency ON price_list (currency);

CREATE TRIGGER trg_price_list_updated_at
    BEFORE UPDATE ON price_list
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Price list entries: (price_list × product × min-qty tier) → price
--
-- A single price_list holds many entries. To support tiered wholesale pricing
-- (e.g. 1+ bags @ $18, 10+ @ $17, 50+ @ $16) we store min_quantity per entry.
-- The storefront picks the entry with the largest min_quantity <= requested qty.
-- -----------------------------------------------------------------------------
CREATE TABLE price_list_entry (
    id             BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    price_list_id  BIGINT         NOT NULL,
    product_id     BIGINT         NOT NULL,
    price          DECIMAL(19,4)  NOT NULL,
    min_quantity   DECIMAL(10,3)  NOT NULL DEFAULT 1.000,
    created_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at     TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_price_entry UNIQUE (price_list_id, product_id, min_quantity),
    CONSTRAINT fk_price_entry_list    FOREIGN KEY (price_list_id) REFERENCES price_list(id) ON DELETE CASCADE,
    CONSTRAINT fk_price_entry_product FOREIGN KEY (product_id)    REFERENCES product(id)    ON DELETE CASCADE
);

CREATE INDEX ix_price_entry_product ON price_list_entry (product_id);

CREATE TRIGGER trg_price_list_entry_updated_at
    BEFORE UPDATE ON price_list_entry
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- -----------------------------------------------------------------------------
-- Inventory (product-level for MVP; variant_id NULL always for now)
-- -----------------------------------------------------------------------------
CREATE TABLE inventory (
    id                  BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    product_id          BIGINT         NOT NULL,
    variant_id          BIGINT         NULL,
    quantity            DECIMAL(12,3)  NOT NULL DEFAULT 0,
    reserved_quantity   DECIMAL(12,3)  NOT NULL DEFAULT 0,
    restock_threshold   DECIMAL(12,3)  NULL,
    updated_at          TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_inventory_product_variant UNIQUE (product_id, variant_id),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE
);

CREATE TRIGGER trg_inventory_updated_at
    BEFORE UPDATE ON inventory
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

