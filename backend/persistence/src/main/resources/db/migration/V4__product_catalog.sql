-- Wholesale price lists — one per B2B group, USD-priced
INSERT INTO price_list (customer_group_id, name, currency, active)
SELECT g.id, 'Wholesale — ' || g.name || ' (USD)', 'USD', TRUE
FROM customer_group g
WHERE g.code IN ('WHOLESALE_T1', 'WHOLESALE_T2', 'VIP');

-- Populate wholesale entries at ~20% (T1), ~30% (T2), ~35% (VIP) off retail.
INSERT INTO price_list_entry (price_list_id, product_id, price, min_quantity)
SELECT
    pl.id AS price_list_id,
    p.id  AS product_id,
    ROUND(p.base_price * (
        CASE g.code
            WHEN 'WHOLESALE_T1' THEN 0.80
            WHEN 'WHOLESALE_T2' THEN 0.70
            WHEN 'VIP'          THEN 0.65
        END
    ), 4) AS price,
    (CASE g.code
        WHEN 'WHOLESALE_T1' THEN 10.000
        WHEN 'WHOLESALE_T2' THEN 25.000
        WHEN 'VIP'          THEN 50.000
    END) AS min_quantity
FROM price_list pl
JOIN customer_group g ON g.id = pl.customer_group_id
CROSS JOIN product p
WHERE p.status = 'ACTIVE';

